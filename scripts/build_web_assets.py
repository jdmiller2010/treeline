#!/usr/bin/env python3
"""Turn the design kit's icons, illustrations and brand mark into one JS
module, web/shared/assets.js, so the apps use the kit's exact markup.

Run after the design kit changes:  python3 scripts/build_web_assets.py
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
UI = ROOT / "design" / "ui"
OUT = ROOT / "web" / "shared" / "assets.js"


def icons():
    out = {}
    for f in sorted((UI / "icons").glob("*.svg")):
        inner = re.search(r"<svg[^>]*>(.*)</svg>", f.read_text(), re.S).group(1)
        out[f.stem] = inner.strip()
    return out


def art():
    text = (UI / "components" / "Illustration.html").read_text()
    out = {}
    for name, svg in re.findall(r"<!-- (\w+) -->\s*(<svg.*?</svg>)", text, re.S):
        # Sized by the page, not by the file.
        svg = re.sub(r'\swidth="\d+"', "", svg, count=1)
        out[name] = svg
    return out


def brand():
    text = (UI / "components" / "NavBar.html").read_text()
    m = re.search(r'<!-- Brand.*?-->\s*(<a class="tl-brand".*?</a>)', text, re.S)
    return m.group(1)


def main():
    OUT.write_text(
        "// Generated by scripts/build_web_assets.py from design/ui. Do not edit.\n"
        f"export const ICONS = {json.dumps(icons(), indent=1)};\n"
        f"export const ART = {json.dumps(art(), indent=1)};\n"
        f"export const BRAND = {json.dumps(brand())};\n")
    print("wrote", OUT.relative_to(ROOT), f"({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
