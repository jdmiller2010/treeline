#!/usr/bin/env python3
"""Build the public legal pages from docs/legal/*.md:

  docs/legal/terms.md           ->  web/legal/terms/index.html           (/legal/terms/)
  docs/legal/privacy.md         ->  web/legal/privacy/index.html         (/legal/privacy/)
  docs/legal/acceptable-use.md  ->  web/legal/acceptable-use/index.html  (/legal/acceptable-use/)

The markdown files are the one source; the pages are generated (./dev check regenerates them and fails if they were stale).
HTML comments (the owner's TODO notes) are dropped, everything else is escaped, and only the markdown these documents use
is understood: front matter, # to ###, paragraphs, > quotes, * - and 1. lists (with indented continuation and nested
lists), tables, ---, **bold**, *italic*, `code` and [links](...). Links to the other .md files become their page URLs.

Run after changing a policy:  python3 scripts/build_legal.py
"""

import html
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "legal"
OUT = ROOT / "web" / "legal"
DOCS = ("terms", "privacy", "acceptable-use")

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{title} · Treeline</title>
<meta name="description" content="{description}">
<meta name="theme-color" content="#f0e7d3">
<link rel="stylesheet" href="/ui/css/tokens.css">
<link rel="stylesheet" href="/ui/css/treeline.css">
<link rel="icon" href="/ui/logo/exports/favicon.svg" type="image/svg+xml">
</head>
<body class="tl-root" style="margin:0">
<!-- Generated by scripts/build_legal.py from docs/legal/{name}.md. Edit that file, not this one. -->
<main class="tl-page tl-page--narrow" id="main">
<div class="tl-stack tl-stack--sections">
<div class="tl-stack tl-stack--related">
  <a href="/" aria-label="Treeline"><img src="/ui/logo/treeline-lockup.svg" width="200" height="auto" alt="Treeline" style="max-width:100%;height:auto"></a>
  {h1}
  {nav}
</div>
{body}
<div id="footer"></div>
</div>
</main>
<script type="module" src="/legal/legal.js"></script>
</body>
</html>
"""

NAMES = {"terms": "Terms of Service", "privacy": "Privacy Policy", "acceptable-use": "Acceptable Use Policy"}


def slug(text):
    """GitHub's heading anchors, so links like privacy.md#kids-privacy work the same on GitHub and on the page."""
    text = re.sub(r"<[^>]+>", "", text).lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def href(url):
    m = re.fullmatch(r"(terms|privacy|acceptable-use)\.md(#[\w-]+)?", url)
    if m:
        return f"/legal/{m.group(1)}/{m.group(2) or ''}"
    return url


def icon(name):
    svg = (ROOT / "design" / "ui" / "icons" / f"{name}.svg").read_text()
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip()
    return ('<svg class="tl-icon" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" '
            f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{inner}</svg>')


def inline(text):
    text = html.escape(text.strip(), quote=True)
    # Code spans first, set aside, so nothing inside backticks is read as a link or emphasis (as GitHub shows it).
    spans = []
    text = re.sub(r"`([^`]+)`", lambda m: (spans.append(m.group(1)), f"\x00{len(spans) - 1}\x00")[1], text)

    def link(m):
        url = href(html.unescape(m.group(2)))
        external = url.startswith("http")
        rel = ' rel="noopener"' if external else ""
        return f'<a href="{html.escape(url, quote=True)}"{rel}>{m.group(1)}</a>'
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, text)
    text = re.sub(r"\*\*\*(.+?)\*\*\*", r"<strong><em>\1</em></strong>", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    return re.sub(r"\x00(\d+)\x00", lambda m: f"<code>{spans[int(m.group(1))]}</code>", text)


LIST = re.compile(r"^([*-]|\d+\.) +")
# What may start a list in the middle of a paragraph (CommonMark): a bullet, or an ordered list that starts at 1. A wrapped line
# that happens to begin "2026. " stays part of its paragraph.
INTERRUPTS = re.compile(r"^([*-]|1\.) +")


def indent(line):
    return len(line) - len(line.lstrip(" "))


def blocks(lines):
    """Render a list of lines (already dedented) as HTML blocks."""
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s:
            i += 1
        elif s.startswith("### "):
            out.append(f'<h3 class="title-md" id="{slug(s[4:])}">{inline(s[4:])}</h3>')
            i += 1
        elif s.startswith("## "):
            out.append(f'<h2 class="title-lg" id="{slug(s[3:])}">{inline(s[3:])}</h2>')
            i += 1
        elif s == "---":
            out.append('<hr style="border:0;border-top:1px solid var(--line, currentColor);opacity:.4;width:100%">')
            i += 1
        elif s.startswith(">"):
            quote = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                quote.append(lines[i].strip()[1:].strip())
                i += 1
            title, rest = quote[0], " ".join(quote[1:])
            out.append(f'<div class="tl-alert tl-alert--info" role="note"><span class="tl-alert__icon" aria-hidden="true">{icon("info")}</span>'
                       f'<div><p class="tl-alert__title">{inline(title)}</p>'
                       + (f'<p class="tl-alert__body">{inline(rest)}</p>' if rest else "") + "</div></div>")
        elif s.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-+:?", c) for c in cells):
                    rows.append(cells)
                i += 1
            head, body = rows[0], rows[1:]
            out.append('<div class="tl-card"><div class="tl-stack tl-stack--group">')
            for r in body:
                out.append('<dl class="tl-dl">' + "".join(
                    f'<div class="tl-dl__row"><dt>{inline(k)}</dt><dd>{inline(v)}</dd></div>' for k, v in zip(head, r)) + "</dl>")
            out.append("</div></div>")
        elif LIST.match(s):
            ordered = s[0].isdigit()
            base = indent(line)
            items = []
            while i < len(lines):
                cur = lines[i]
                if cur.strip() and indent(cur) == base and LIST.match(cur.strip()) and cur.strip()[0].isdigit() == ordered:
                    items.append([LIST.sub("", cur.strip())])
                    i += 1
                elif cur.strip() and indent(cur) > base and items:
                    items[-1].append(cur)
                    i += 1
                elif not cur.strip() and items:
                    nxt = next((ln for ln in lines[i + 1:] if ln.strip()), None)
                    if nxt is not None and indent(nxt) > base:
                        items[-1].append("")
                    elif not (nxt is not None and indent(nxt) == base and LIST.match(nxt.strip())
                              and nxt.strip()[0].isdigit() == ordered):
                        break
                    i += 1
                else:
                    break
            tag = "ol" if ordered else "ul"
            out.append(f'<{tag} class="tl-measure">')
            for first, *more in items:
                lead = [first]
                while more and more[0].strip() and not LIST.match(more[0].strip()):
                    lead.append(more.pop(0))
                pad = min((indent(m) for m in more if m.strip()), default=0)
                rest = blocks([m[pad:] for m in more])
                out.append(f"<li>{inline(' '.join(x.strip() for x in lead))}{rest}</li>")
            out.append(f"</{tag}>")
        else:
            para = []
            while i < len(lines) and lines[i].strip() and not re.match(r"(#{2,3} |>|\||---$)", lines[i].strip()) \
                    and not (para and INTERRUPTS.match(lines[i].strip())) and not (not para and LIST.match(lines[i].strip())):
                para.append(lines[i].strip())
                i += 1
            # Only a paragraph that is one italic run (the "Last updated" line, the credit) is a caption: never a line that merely
            # starts with bold and ends with italics, which could be a safety statement.
            cls = "caption" if len(para) == 1 and re.fullmatch(r"\*[^*].*[^*]\*", para[0]) and "**" not in para[0] else "tl-measure"
            out.append(f'<p class="{cls}">{inline(" ".join(para))}</p>')
    return "\n".join(out)


def render(name):
    text = (SRC / f"{name}.md").read_text()
    meta = {}
    fm = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if fm:
        for line in fm.group(1).splitlines():
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip()
        text = text[fm.end():]
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    lines = [ln.rstrip() for ln in text.splitlines()]
    h1 = next(ln[2:] for ln in lines if ln.startswith("# "))
    lines = [ln for ln in lines if not ln.startswith("# ")]
    nav = " · ".join(f'<a href="/legal/{d}/">{NAMES[d]}</a>' if d != name else f'<strong>{NAMES[d]}</strong>' for d in DOCS)
    return PAGE.format(title=html.escape(meta.get("title", h1)), description=html.escape(meta.get("description", ""), quote=True),
                       name=name, h1=f'<h1 class="display-md">{inline(h1)}</h1>',
                       nav=f'<p class="caption">{nav}</p>', body=blocks(lines))


def main():
    for name in DOCS:
        path = OUT / name / "index.html"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(name))
        print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
