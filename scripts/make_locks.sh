#!/usr/bin/env bash
# Regenerate the hash-pinned dependency locks used on the VM, in a throwaway python:3.12 container (the VM's Python
# on Ubuntu 24.04 is 3.12). Run it when controller/requirements.txt or deploy/native/requirements-tools.in changes,
# review the diff, commit. Nothing downloaded here is executed on this machine.
#
#   controller/requirements.txt          -> controller/requirements-prod.lock   (the app: flask, gunicorn, pywebpush ...)
#   deploy/native/requirements-tools.in  -> deploy/native/requirements-tools.lock (boto3, for the root-run tools)
#
#   infra/requirements.in                -> infra/requirements.lock            (the CDK app: aws-cdk-lib, constructs)
#
# The locks name the sha256 of each wheel for CPython 3.12 on x86_64 Linux (Lightsail's Linux plans are x86_64).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
lock() {   # lock INPUT OUTPUT
  docker run --rm -v "$ROOT:/r" python:3.12-slim sh -c '
set -e
python -m venv /v >/dev/null
/v/bin/pip install -q --disable-pip-version-check -r "/r/$1"
/v/bin/pip freeze --exclude pip --exclude setuptools > /tmp/freeze.txt
mkdir /w && /v/bin/pip download -q --disable-pip-version-check --no-deps -r /tmp/freeze.txt -d /w
{
  echo "# Generated by scripts/make_locks.sh from $1: exact versions and the sha256 of each wheel (CPython 3.12, x86_64 Linux)."
  echo "# Install with: pip install --require-hashes --no-deps -r <this file>"
  while IFS= read -r line; do
    name="${line%%==*}"; ver="${line##*==}"
    pat="$(echo "$name" | sed "s/[-_.]/[-_.]/g")-$ver"
    files=$(ls /w | grep -i "^$pat" || true)
    [ -n "$files" ] || { echo "no file for $line" >&2; exit 1; }
    printf "%s==%s" "$name" "$ver"
    for f in $files; do printf " %s\n    --hash=%s" "$(printf "\134")" "$(/v/bin/pip hash "/w/$f" | sed -n 2p | sed "s/--hash=//")"; done
    echo
  done < /tmp/freeze.txt
} > "/r/$2"' _ "$1" "$2"
}
# With no argument all three are rebuilt (and unpinned ">=" inputs may move to newer versions: review the diff).
# `scripts/make_locks.sh infra` (or app, tools) rebuilds just one.
want="${1:-all}"
[ "$want" != all ] && [ "$want" != app ] || lock controller/requirements.txt controller/requirements-prod.lock
[ "$want" != all ] && [ "$want" != tools ] || lock deploy/native/requirements-tools.in deploy/native/requirements-tools.lock
[ "$want" != all ] && [ "$want" != infra ] || lock infra/requirements.in infra/requirements.lock
