"""Writes the PJSIP accounts for every handset, and tells Asterisk to reload.

Asterisk stores only an md5 digest of each handset's secret (`md5_cred`), so
the real secret exists only on the handset itself.
"""

import os

from . import ari, db

GENERATED = os.environ.get("TREELINE_PJSIP_FILE", "/generated/pjsip_handsets.conf")


def render(conn):
    out = ["; Generated by the Treeline API. Do not edit by hand.\n"]
    rows = conn.execute("SELECT h.* FROM handset h JOIN treehouse t ON t.id=h.treehouse_id "
                        "WHERE h.removed_at IS NULL AND t.left_at IS NULL AND t.archived_at IS NULL ORDER BY h.id")
    for h in rows:
        u = h["sip_user"]
        template = "webrtc-endpoint" if h["kind"] == "softphone" else "phone-endpoint"
        aor_template = "webrtc-aor" if h["kind"] == "softphone" else "phone-aor"
        out.append(
            f"[{u}]({template})\n"
            f"auth={u}\naors={u}\n"
            # The caller ID is fixed to the account name so a handset can't
            # pretend to be another one.
            f'callerid="{u}" <{u}>\n\n'
            f"[{u}]\ntype=auth\nauth_type=md5\nusername={u}\nrealm={db.SIP_REALM}\n"
            f"md5_cred={h['sip_md5']}\n\n"
            f"[{u}]({aor_template})\n\n")
    return "".join(out)


def write(conn, path=None, reload=True, client=None):
    """Write the file atomically and ask Asterisk to reload PJSIP."""
    path = path or GENERATED
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    text = render(conn)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)
    if reload:
        (client or ari.Ari()).reload_module("res_pjsip.so")
